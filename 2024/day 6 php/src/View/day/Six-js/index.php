    class Grid {
        constructor(x, y, obstacle = false, visaed = false) {
            this.x = x;
            this.y = y;
            this.obstacle = obstacle;
            this.visaed = visaed;
        }
    }
    class Player {
        constructor(x, y, direction) {
            this.x = x;
            this.y = y;
            this.direction = direction;
        }

        move(direction) {
            switch (direction) {
                case Direction.UP:
                    this.y--;
                    break;
                case Direction.DOWN:
                    this.y++;
                    break;
                case Direction.LEFT:
                    this.x--;
                    break;
                case Direction.RIGHT:
                    this.x++;
                    break;
            }
        }
        nextDirection() {
            switch (this.direction) {
                case Direction.UP:
                    this.direction = Direction.RIGHT;
                    break;
                case Direction.DOWN:
                    this.direction = Direction.LEFT;
                    break;
                case Direction.LEFT:
                    this.direction = Direction.UP;
                    break;
                case Direction.RIGHT:
                    this.direction = Direction.DOWN;
                    break;
            }
        }
    }
    const Direction = {
        UP: 'UP',
        DOWN: 'DOWN',
        LEFT: 'LEFT',
        RIGHT: 'RIGHT'
    };
    let grids = [];
    let player = null;
    for (let y = 0; y < example.length; y++) {
        const row = example[y];

        for (let x = 0; x < row.length; x++) {
            if (row[x] === '#') {
                // Initialize obstacle grid cell
                grids.push(new Grid(x, y, true));
            } else if (row[x] === '^') {
                // Initialize player at the first position with a direction
                grids.push(new Grid(x, y, false, true));
                player = new Player(x, y, Direction.UP);
            } else {
                // Initialize empty grid cell
                grids.push(new Grid(x, y));
            }
        }
    }

    function nextPlayerCanMove(player, grids) {
        let y = player.y;
        let x = player.x;

        switch (player.direction) {
            case Direction.UP:
                y--;
                break;
            case Direction.DOWN:
                y++;
                break;
            case Direction.LEFT:
                x--;
                break;
            case Direction.RIGHT:
                x++;
                break;
        }
        // Check if the next position is within bounds and not an obstacle
        if (x < 0 || y < 0 || y >= grids.length || x >= grids[0].length) {
            return false; // Out of bounds
        }

        const grid = grids.find(currentGrid => currentGrid.x === x && currentGrid.y === y);

        return grid instanceof Grid && grid.obstacle;
    }


    while (true) {
        if (player === null) {
            console.error("Player not initialized.");
            break;
        }
        const {
            x,
            y
        } = player;

        if (x <= 0 || x >= grids[0].length || y <= 0 || y >= grids.length) {
            console.log(`Player out of bounds. Position: (${x}, ${y})`);
            break; // Player is out of bounds
        }

        if (nextPlayerCanMove(player, grids)) {
            player.nextDirection();
        }

        player.move(player.direction);
        const currentGrid = grids.find(grid => grid.x === player.x && grid.y === player.y);
        if (currentGrid) {
            currentGrid.visaed = true; // Mark the current grid as visited
        } else {
            console.error("Current grid not found for player position.");
            break;
        }
    }

    let result = grids.reduce((acc, grid) => {
        return acc += grid.visaed ? 1 : 0;
    }, 0);

    console.log(`Total visited cells: ${result}`);
